using System.Globalization;
using Osctl.Processes;

namespace Osctl.Running;

/// <summary>The state of an instance's console pane.</summary>
public sealed record PaneState(bool Exists, bool Dead, int Pid, int ExitStatus, int Signal);

/// <summary>
/// One instance's tmux server (PLAN.md "Running instances"): its own socket, one session named after the instance,
/// one window whose pane runs OpenSim. <c>remain-on-exit</c> keeps the dead pane so its exit status can be read.
/// </summary>
public sealed class Tmux(IProcessRunner runner, string socket, string session)
{
    public string Socket { get; } = socket;

    public string Session { get; } = session;

    private string Target => $"={Session}:0.0";

    /// <summary>Starts the server and session running <paramref name="command"/> (as given: no shell) in <paramref name="directory"/>.</summary>
    public async Task StartAsync(string configFile, string directory, IReadOnlyList<string> command, CancellationToken ct)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Socket)!);
        await RunAsync(["-f", configFile, "new-session", "-d", "-s", Session, "-n", Session, "-x", "200", "-y", "50", "-c", directory,
            .. command], change: true, ct);
    }

    /// <summary>Copies everything the pane shows into a file (the console log).</summary>
    public Task PipeToAsync(string file, CancellationToken ct) =>
        RunAsync(["pipe-pane", "-t", Target, "-o", $"cat >> {Processes.ShellQuote.Quote(file)}"], change: true, ct);

    /// <summary>Lets other users attach (tmux 3.3's server-access); the socket's mode must allow them too.</summary>
    public Task AllowAsync(string user, CancellationToken ct) =>
        RunAsync(["server-access", "-a", user], change: true, ct, check: false);

    public async Task<PaneState> StateAsync(CancellationToken ct)
    {
        var r = await runner.RunAsync("tmux",
            ["-S", Socket, "display-message", "-p", "-t", Target, "#{pane_dead} #{pane_pid} #{pane_dead_status} #{pane_dead_signal}"],
            cancellationToken: ct);
        if (!r.Succeeded)
            return new PaneState(false, true, 0, 0, 0);
        var parts = r.StandardOutput.Trim().Split(' ');
        int At(int i) => i < parts.Length && int.TryParse(parts[i], NumberStyles.Integer, CultureInfo.InvariantCulture, out var v) ? v : 0;
        return new PaneState(true, At(0) == 1, At(1), At(2), At(3));
    }

    /// <summary>Types a line into the console, as someone at the keyboard would.</summary>
    public async Task SendLineAsync(string text, CancellationToken ct)
    {
        await RunAsync(["send-keys", "-t", Target, "-l", text], change: true, ct);
        await RunAsync(["send-keys", "-t", Target, "Enter"], change: true, ct);
    }

    public Task KillAsync(CancellationToken ct) =>
        RunAsync(["kill-server"], change: true, ct, check: false);

    public async Task<bool> IsRunningAsync(CancellationToken ct) =>
        File.Exists(Socket) && (await runner.RunAsync("tmux", ["-S", Socket, "has-session", "-t", $"={Session}"], cancellationToken: ct)).Succeeded;

    /// <summary>The tmux configuration for a console: osctl.ini's prefix and scrollback, and nothing that closes a dead pane.</summary>
    public static string Config(string prefix, int historyLimit, string session) => $"""
        # Generated by osctl for instance '{session}': rewritten at every start.
        set -g prefix {prefix}
        unbind C-b
        bind {prefix} send-prefix
        set -g history-limit {historyLimit.ToString(CultureInfo.InvariantCulture)}
        set -g remain-on-exit on
        set -g exit-empty on
        set -g status-left "[{session}] "
        set -g status-right "osctl console: {prefix} d to leave"
        set -g status-right-length 40

        """;

    private async Task<ProcessResult> RunAsync(IReadOnlyList<string> args, bool change, CancellationToken ct, bool check = true)
    {
        var r = await runner.RunAsync("tmux", ["-S", Socket, .. args], change ? ProcessRunOptions.Change : ProcessRunOptions.Query, ct);
        if (r.NotFound)
            throw new OsctlException("tmux is not installed (sudo apt install tmux)");
        if (check && !r.Succeeded)
            throw new OsctlException($"{ShellQuote.Describe("tmux", ["-S", Socket, .. args])} failed: {r.StandardError.Trim()}");
        return r;
    }
}
