using System.Globalization;
using Osctl.Instances;
using Osctl.Processes;
using Osctl.Settings;

namespace Osctl.Running;

public enum InstanceState
{
    Stopped,
    Starting,
    Running,
    Stopping,

    /// <summary>Crashed too often, too quickly (systemd's start limit): left stopped until started by hand.</summary>
    Broken,

    /// <summary>Ended with an error once (systemd will restart it, or a direct run is over).</summary>
    Failed,
}

/// <summary>What <c>osctl status</c> shows for one instance.</summary>
public sealed record InstanceStatus(
    string Name,
    InstanceState State,
    bool StartsAtBoot,
    int OpenSimPid,
    DateTimeOffset? Since,
    string? Release,
    int Restarts,
    string? Detail);

/// <summary>Starts and stops instances: through systemd, or directly (PLAN.md "Running instances").</summary>
public interface ISupervisor
{
    Task StartAsync(string name, CancellationToken ct);

    Task StopAsync(string name, bool force, CancellationToken ct);

    Task RestartAsync(string name, CancellationToken ct);

    Task SetBootAsync(string name, bool enabled, CancellationToken ct);

    Task<InstanceStatus> StatusAsync(string name, CancellationToken ct);
}

/// <summary>The unit name for an instance, and where osctl's own program is.</summary>
public static class Units
{
    public static string For(string instance) => $"osctl@{instance}.service";

    /// <summary>How to run this osctl again: the apphost, or dotnet with the dll when run that way.</summary>
    public static IReadOnlyList<string> Self()
    {
        var process = Environment.ProcessPath ?? "osctl";
        return Path.GetFileNameWithoutExtension(process) == "dotnet"
            ? [process, Path.Combine(AppContext.BaseDirectory, "osctl.dll")]
            : [process];
    }

    /// <summary>
    /// The template unit (PLAN.md "Running instances"). Restart limits and timeouts come from osctl.ini, so
    /// 'osctl units install' writes it again after they change.
    /// </summary>
    public static string Template(OsctlSettings settings, OsctlPaths paths, bool user, IReadOnlyList<string> osctl)
    {
        var root = paths.Root == "/" ? "" : $" --root {ShellQuote.Quote(paths.Root)}";
        var program = string.Join(' ', osctl.Select(ShellQuote.Quote));
        string N(int n) => n.ToString(CultureInfo.InvariantCulture);
        var account = user ? "" : $"User={settings.Account.User}\nGroup={settings.Account.Group}\n";
        return $"""
            # Generated by osctl ('osctl units install{(user ? " --user" : "")}'): one OpenSimulator instance, %i.
            [Unit]
            Description=OpenSimulator instance %i (osctl)
            Wants=network-online.target
            After=network-online.target mariadb.service mysql.service
            # More than MaxRestarts crashes within IntervalSeconds ([Restart] in osctl.ini): the instance is broken.
            StartLimitIntervalSec={N(settings.Restart.IntervalSeconds)}
            StartLimitBurst={N(settings.Restart.MaxRestarts + 1)}

            [Service]
            Type=notify
            NotifyAccess=main
            {account}ExecStart={program}{root} run %i
            ExecStop={program}{root} run-stop %i
            TimeoutStartSec={N(settings.Timeouts.StartSeconds + 60)}
            TimeoutStopSec={N(settings.Timeouts.StopSeconds + 30)}
            Restart=on-failure
            RestartSec={N(settings.Restart.DelaySeconds)}
            KillMode=control-group
            LimitSTACK=1G
            LimitNOFILE=65536
            UMask=0007

            [Install]
            WantedBy={(user ? "default.target" : "multi-user.target")}

            """;
    }
}

/// <summary>Instances as systemd units (<c>osctl@&lt;name&gt;.service</c>), system or user.</summary>
public sealed class SystemdSupervisor(IProcessRunner runner, InstanceStore instances, bool user) : ISupervisor
{
    public async Task StartAsync(string name, CancellationToken ct)
    {
        var properties = await ShowAsync(name, ct);
        if (properties.GetValueOrDefault("ActiveState") == "failed")
            await SystemctlAsync(ct, "reset-failed", Units.For(name));
        await SystemctlAsync(ct, "start", Units.For(name));
    }

    public async Task StopAsync(string name, bool force, CancellationToken ct)
    {
        if (force)
            await SystemctlAsync(ct, "kill", "--signal=SIGKILL", Units.For(name));
        await SystemctlAsync(ct, "stop", Units.For(name));
    }

    public async Task RestartAsync(string name, CancellationToken ct)
    {
        var properties = await ShowAsync(name, ct);
        if (properties.GetValueOrDefault("ActiveState") == "failed")
            await SystemctlAsync(ct, "reset-failed", Units.For(name));
        await SystemctlAsync(ct, "restart", Units.For(name));
    }

    public Task SetBootAsync(string name, bool enabled, CancellationToken ct) =>
        SystemctlAsync(ct, enabled ? "enable" : "disable", Units.For(name));

    public async Task<InstanceStatus> StatusAsync(string name, CancellationToken ct)
    {
        var p = await ShowAsync(name, ct);
        if (p.GetValueOrDefault("LoadState") == "not-found")
            throw new OsctlException($"The systemd unit osctl@.service is not installed: run 'osctl units install{(user ? " --user" : "")}'");

        var run = RunState.Load(instances.RunStateFile(name));
        var restarts = int.TryParse(p.GetValueOrDefault("NRestarts"), out var n) ? n : 0;
        // With Restart=on-failure a unit that stays failed after restarts means systemd gave up: its start limit
        // ("Start request repeated too quickly"). systemd 259 keeps Result at the last exit code then.
        var state = (p.GetValueOrDefault("ActiveState"), restarts > 0 ? "restarted" : "", p.GetValueOrDefault("Result")) switch
        {
            ("active", _, _) => InstanceState.Running,
            ("activating", _, _) or ("reloading", _, _) => InstanceState.Starting,
            ("deactivating", _, _) => InstanceState.Stopping,
            ("failed", _, "start-limit-hit") or ("failed", "restarted", _) => InstanceState.Broken,
            ("failed", _, _) => InstanceState.Failed,
            _ => InstanceState.Stopped,
        };
        var stamp = p.GetValueOrDefault("ActiveEnterTimestamp") ?? "";
        var since = stamp.StartsWith('@') && long.TryParse(stamp[1..], NumberStyles.None, CultureInfo.InvariantCulture, out var seconds)
            ? DateTimeOffset.FromUnixTimeSeconds(seconds)
            : run?.Started;
        var boot = p.GetValueOrDefault("UnitFileState") is "enabled";
        var detail = state switch
        {
            InstanceState.Broken => $"crashed {restarts + 1} times too quickly; 'osctl start {name}' tries again",
            InstanceState.Failed => $"systemd: {p.GetValueOrDefault("Result")}",
            _ => null,
        };
        return new InstanceStatus(name, state, boot, state is InstanceState.Running or InstanceState.Starting ? run?.OpenSimPid ?? 0 : 0,
            state is InstanceState.Running or InstanceState.Starting ? since : null, run?.Release, restarts, detail);
    }

    private async Task<Dictionary<string, string>> ShowAsync(string name, CancellationToken ct)
    {
        var r = await runner.RunAsync("systemctl",
            [.. Scope(), "show", Units.For(name), "--timestamp=unix", "--property=LoadState,ActiveState,SubState,Result,UnitFileState,NRestarts,ActiveEnterTimestamp"],
            cancellationToken: ct);
        if (r.NotFound)
            throw new OsctlException("systemctl not found: set [Supervisor] Mode = direct in osctl.ini to run instances without systemd");
        var properties = new Dictionary<string, string>();
        foreach (var line in r.StandardOutput.Split('\n', StringSplitOptions.RemoveEmptyEntries))
        {
            var eq = line.IndexOf('=');
            if (eq > 0)
                properties[line[..eq]] = line[(eq + 1)..].Trim();
        }
        return properties;
    }

    private async Task SystemctlAsync(CancellationToken ct, params string[] args)
    {
        var r = await runner.RunAsync("systemctl", [.. Scope(), .. args], ProcessRunOptions.Change, ct);
        if (r.NotFound)
            throw new OsctlException("systemctl not found: set [Supervisor] Mode = direct in osctl.ini to run instances without systemd");
        if (!r.Succeeded)
            throw new OsctlException($"systemctl {string.Join(' ', [.. Scope(), .. args])} failed: {r.StandardError.Trim()}" +
                (args[0] is "start" or "restart" ? $" ('osctl logs {args[^1].Replace("osctl@", "").Replace(".service", "")}' shows why)" : ""));
    }

    private string[] Scope() => user ? ["--user"] : [];
}

/// <summary>
/// No systemd ([Supervisor] Mode = direct): osctl starts the runner in the background itself. There is no restart
/// after a crash and nothing starts at boot; for development and tests.
/// </summary>
public sealed class DirectSupervisor(
    OsctlPaths paths,
    OsctlSettings settings,
    IProcessRunner runner,
    IRemoteAdmin remoteAdmin,
    TimeProvider time,
    IReadOnlyList<string> osctl) : ISupervisor
{
    private static readonly TimeSpan Poll = TimeSpan.FromMilliseconds(500);
    private readonly InstanceStore instances = new(paths);

    public async Task StartAsync(string name, CancellationToken ct)
    {
        if (RunState.Load(instances.RunStateFile(name)) is { IsRunnerAlive: true })
            return;

        var runnerLog = Path.Combine(instances.LogDir(name), "runner.log");
        Directory.CreateDirectory(Path.GetDirectoryName(runnerLog)!);
        File.Delete(instances.RunStateFile(name));
        // setsid -f: the runner gets its own session and outlives this command and its terminal.
        var line = string.Join(' ', [.. osctl.Select(ShellQuote.Quote), "--root", ShellQuote.Quote(paths.Root), "run", ShellQuote.Quote(name)]);
        var r = await runner.RunAsync("setsid", ["-f", "sh", "-c", $"exec {line} >> {ShellQuote.Quote(runnerLog)} 2>&1 < /dev/null"],
            ProcessRunOptions.Change, ct);
        if (!r.Succeeded)
            throw new OsctlException($"Could not start the runner for '{name}': {r.StandardError.Trim()}");

        var deadline = time.GetUtcNow() + TimeSpan.FromSeconds(settings.Timeouts.StartSeconds + 30);
        var seen = false;
        while (time.GetUtcNow() < deadline)
        {
            await Task.Delay(Poll, ct);
            var state = RunState.Load(instances.RunStateFile(name));
            if (state is { Ready: not null })
                return;
            if (state is not null)
                seen = true;
            if ((seen && state is null) || (state is not null && !state.IsRunnerAlive))
                throw new OsctlException($"'{name}' did not start; 'osctl logs {name}' and {runnerLog} show why");
            if (!seen && time.GetUtcNow() > deadline - TimeSpan.FromSeconds(settings.Timeouts.StartSeconds))
                throw new OsctlException($"The runner for '{name}' did not start; see {runnerLog}");
        }
        throw new OsctlException($"'{name}' was not ready within {settings.Timeouts.StartSeconds + 30} s; 'osctl logs {name}'");
    }

    public async Task StopAsync(string name, bool force, CancellationToken ct)
    {
        var state = RunState.Load(instances.RunStateFile(name));
        // The stopper's messages go to the runner's log, with the rest of the instance's story.
        Directory.CreateDirectory(instances.LogDir(name));
        await using (var log = new StreamWriter(Path.Combine(instances.LogDir(name), "runner.log"), append: true) { AutoFlush = true })
            await new InstanceStopper(paths, settings, runner, remoteAdmin, log, time).StopAsync(name, force, ct);
        for (var i = 0; i < 40 && state is { IsRunnerAlive: true }; i++)
            await Task.Delay(Poll, ct);
    }

    public async Task RestartAsync(string name, CancellationToken ct)
    {
        await StopAsync(name, force: false, ct);
        await StartAsync(name, ct);
    }

    public Task SetBootAsync(string name, bool enabled, CancellationToken ct) => Task.CompletedTask;

    public Task<InstanceStatus> StatusAsync(string name, CancellationToken ct)
    {
        var run = RunState.Load(instances.RunStateFile(name));
        var state = run switch
        {
            null => InstanceState.Stopped,
            { IsRunnerAlive: false } => InstanceState.Failed,
            { Stopping: true } => InstanceState.Stopping,
            { Ready: null } => InstanceState.Starting,
            _ => InstanceState.Running,
        };
        var live = state is InstanceState.Running or InstanceState.Starting or InstanceState.Stopping;
        return Task.FromResult(new InstanceStatus(name, state, false, live ? run!.OpenSimPid : 0, live ? run!.Started : null,
            run?.Release, 0, state == InstanceState.Failed ? "the runner is gone without cleaning up" : null));
    }
}
