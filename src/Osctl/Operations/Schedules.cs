using System.Globalization;
using System.Text.RegularExpressions;
using Osctl.Instances;
using Osctl.Processes;
using Osctl.Settings;

namespace Osctl.Operations;

/// <summary>The two scheduled jobs.</summary>
public enum ScheduledJob
{
    Restart,
    Backup,
}

/// <summary>
/// Scheduled restarts and backups as systemd timers (PLAN.md "Backups and scheduled restarts"). The schedule is kept
/// in instance.ini [Schedule]; each instance with one gets <c>osctl-restart@&lt;name&gt;.timer</c> and/or
/// <c>osctl-backup@&lt;name&gt;.timer</c>, which start the template services <c>osctl-restart@.service</c>
/// (<c>osctl restart --scheduled</c>) and <c>osctl-backup@.service</c> (<c>osctl backup create --scheduled</c>).
/// </summary>
public static partial class Schedules
{
    public static string Kind(ScheduledJob job) => job == ScheduledJob.Restart ? "restart" : "backup";

    public static string TimerName(ScheduledJob job, string instance) => $"osctl-{Kind(job)}@{instance}.timer";

    public static string ServiceName(ScheduledJob job) => $"osctl-{Kind(job)}@.service";

    public static string? Calendar(InstanceSchedule schedule, ScheduledJob job) =>
        job == ScheduledJob.Restart ? schedule.Restart : schedule.Backup;

    public static string UnitDir(bool user) =>
        user ? Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".config", "systemd", "user") : "/etc/systemd/system";

    /// <summary>The template service a job's timers start.</summary>
    public static string Service(ScheduledJob job, OsctlSettings settings, OsctlPaths paths, bool user, IReadOnlyList<string> osctl)
    {
        var root = paths.Root == "/" ? "" : $" --root {ShellQuote.Quote(paths.Root)}";
        var program = string.Join(' ', osctl.Select(ShellQuote.Quote));
        var account = user ? "" : $"User={settings.Account.User}\nGroup={settings.Account.Group}\n";
        var (what, command) = job == ScheduledJob.Restart
            ? ("Scheduled restart", "restart --scheduled %i")
            : ("Scheduled backup", "backup create --scheduled %i");
        return $"""
            # Generated by osctl ('osctl units install{(user ? " --user" : "")}'): started by osctl-{Kind(job)}@%i.timer.
            [Unit]
            Description={what} of OpenSimulator instance %i (osctl)

            [Service]
            Type=oneshot
            {account}ExecStart={program}{root} {command}
            # A restart waits for its warnings, a backup for OpenSim's saves: no time limit.
            TimeoutStartSec=infinity
            UMask=0007

            """;
    }

    public static string Timer(ScheduledJob job, string instance, string calendar) => $"""
        # Generated by osctl from instance.ini [Schedule] of '{instance}': change it with 'osctl schedule {Kind(job)}'.
        [Unit]
        Description=Scheduled {Kind(job)} of OpenSimulator instance {instance} (osctl)

        [Timer]
        OnCalendar={calendar}

        [Install]
        WantedBy=timers.target

        """;

    /// <summary>
    /// Checks a calendar expression with systemd-analyze and returns its next time (local, as systemd prints it), or
    /// null when systemd-analyze is not there to ask.
    /// </summary>
    public static async Task<string?> NextAsync(IProcessRunner runner, string calendar, CancellationToken ct)
    {
        var r = await runner.RunAsync("systemd-analyze", ["calendar", calendar], cancellationToken: ct);
        if (r.NotFound)
            return null;
        if (!r.Succeeded)
            throw new OsctlException($"'{calendar}' is not a systemd calendar expression (e.g. 'Sun 04:00', '*-*-* 03:30', 'daily'): {r.StandardError.Trim()}");
        return NextElapse().Match(r.StandardOutput) is { Success: true } m ? m.Groups[1].Value.Trim() : "?";
    }

    /// <summary>
    /// Writes the instance's timers into <paramref name="unitDir"/> (and removes those it no longer has), then
    /// reloads systemd and enables the timers. Throws UnauthorizedAccessException when the directory is not ours.
    /// </summary>
    public static async Task<IReadOnlyList<string>> InstallTimersAsync(IProcessRunner runner, string unitDir, bool user,
        IEnumerable<InstanceDefinition> instances, bool removeOthers, CancellationToken ct)
    {
        var scope = user ? new[] { "--user" } : [];
        var written = new HashSet<string>(StringComparer.Ordinal);
        var report = new List<string>();
        Directory.CreateDirectory(unitDir);
        var list = instances.ToList();
        foreach (var instance in list)
        {
            foreach (var job in Enum.GetValues<ScheduledJob>())
            {
                if (Calendar(instance.Scheduled, job) is not { } calendar)
                    continue;
                var name = TimerName(job, instance.Name);
                await File.WriteAllTextAsync(Path.Combine(unitDir, name), Timer(job, instance.Name, calendar), ct);
                written.Add(name);
            }
        }

        // Timers of these instances (or of any instance, with removeOthers) that their schedules no longer have.
        var mine = list.Select(i => i.Name).ToHashSet(StringComparer.Ordinal);
        var stale = Directory.GetFiles(unitDir, "osctl-*@*.timer")
            .Select(Path.GetFileName).OfType<string>()
            .Where(f => TimerPattern().Match(f) is { Success: true } m && !written.Contains(f) && (removeOthers || mine.Contains(m.Groups[2].Value)))
            .ToList();
        foreach (var name in stale)
        {
            await runner.RunAsync("systemctl", [.. scope, "disable", "--now", name], ProcessRunOptions.Change, ct);
            File.Delete(Path.Combine(unitDir, name));
            report.Add($"removed {name}");
        }

        var reload = await runner.RunAsync("systemctl", [.. scope, "daemon-reload"], ProcessRunOptions.Change, ct);
        if (reload.NotFound)
            throw new OsctlException("systemctl not found: timers need systemd; with [Supervisor] Mode = direct use cron ('osctl schedule list --cron')");
        foreach (var name in written.Order(StringComparer.Ordinal))
        {
            var r = await runner.RunAsync("systemctl", [.. scope, "enable", "--now", name], ProcessRunOptions.Change, ct);
            report.Add(r.Succeeded ? $"enabled {name}" : $"could not enable {name}: {r.StandardError.Trim()}");
        }
        return report;
    }

    /// <summary>
    /// A crontab line for a job (the direct supervisor has no systemd timers), when the calendar expression is one
    /// cron can say: hourly, daily, weekly, monthly, or [weekdays] HH:MM[:SS] (also as *-*-* HH:MM). Null otherwise.
    /// </summary>
    public static string? CronLine(string calendar, string command)
    {
        var c = calendar.Trim();
        var fields = c.ToLowerInvariant() switch
        {
            "hourly" => "0 * * * *",
            "daily" => "0 0 * * *",
            "weekly" => "0 0 * * 1",
            "monthly" => "0 0 1 * *",
            _ => null,
        };
        if (fields is null && CronCalendar().Match(c) is { Success: true } m)
        {
            var days = m.Groups[1].Success
                ? string.Join(',', m.Groups[1].Value.Split(',', StringSplitOptions.TrimEntries).Select(DayNumber))
                : "*";
            if (days.Contains('?'))
                return null;
            fields = $"{int.Parse(m.Groups[4].Value, CultureInfo.InvariantCulture)} {int.Parse(m.Groups[3].Value, CultureInfo.InvariantCulture)} * * {days}";
        }
        return fields is null ? null : $"{fields} {command}";
    }

    private static string DayNumber(string day) => day.ToLowerInvariant() switch
    {
        "sun" or "sunday" => "0",
        "mon" or "monday" => "1",
        "tue" or "tuesday" => "2",
        "wed" or "wednesday" => "3",
        "thu" or "thursday" => "4",
        "fri" or "friday" => "5",
        "sat" or "saturday" => "6",
        _ => "?",
    };

    [GeneratedRegex(@"^\s*Next elapse:\s*(.+)$", RegexOptions.Multiline)]
    private static partial Regex NextElapse();

    [GeneratedRegex(@"^osctl-(restart|backup)@(.+)\.timer$")]
    private static partial Regex TimerPattern();

    [GeneratedRegex(@"^(?:([A-Za-z]+(?:\s*,\s*[A-Za-z]+)*)\s+)?(\*-\*-\*\s+)?(\d{1,2}):(\d{2})(?::00)?$")]
    private static partial Regex CronCalendar();
}
