using Osctl.Ini;

namespace Osctl.Tests.Ini;

public class IniDocumentTests
{
    [Fact]
    public void MergeOverridesKeysInPlaceAndAppendsNewOnes()
    {
        var a = IniParser.Parse("[S]\nx = 1\ny = 2\n[T]\nt = 1", "a.ini");
        var b = IniParser.Parse("[U]\nu = 1\n[S]\nz = 3\nx = 9", "b.ini");
        a.Merge(b);

        Assert.Equal(["S", "T", "U"], a.Sections.Select(s => s.Name));
        Assert.Equal(["x", "y", "z"], a["S"]!.Keys);
        Assert.Equal("9", a.Get("S", "x"));
        Assert.Equal("b.ini", a["S"]!.GetEntry("x")!.Origin!.Value.File);
        Assert.Equal("a.ini", a["S"]!.GetEntry("y")!.Origin!.Value.File);
    }

    [Fact]
    public void RemoveKeepsTheOrderOfTheRest()
    {
        var doc = IniParser.Parse("[S]\na = 1\nb = 2\nc = 3");
        Assert.True(doc.Remove("S", "a"));
        doc.Set("S", "c", "30");
        doc.Set("S", "d", "4");
        Assert.Equal(["b", "c", "d"], doc["S"]!.Keys);
        Assert.Equal("30", doc.Get("S", "c"));
        Assert.False(doc.Remove("S", "missing"));
    }

    [Fact]
    public void CloneIsIndependent()
    {
        var doc = IniParser.Parse("[S]\na = 1");
        var copy = doc.Clone();
        copy.Set("S", "a", "2");
        Assert.Equal("1", doc.Get("S", "a"));
    }
}

public class IniWriterTests
{
    [Fact]
    public void WritesSectionsAndKeys()
    {
        var doc = new IniDocument();
        doc.Set("Startup", "PIDFile", "/run/osctl/Test1.pid");
        doc.Set("Network", "http_listener_port", "9000");

        Assert.Equal(
            "[Startup]\n    PIDFile = /run/osctl/Test1.pid\n\n[Network]\n    http_listener_port = 9000\n",
            IniWriter.ToText(doc));
    }

    [Fact]
    public void WritesHeaderComments()
    {
        var doc = new IniDocument();
        doc.Set("S", "k", "v");
        Assert.StartsWith("; Generated by osctl\n;\n\n[S]", IniWriter.ToText(doc, ["Generated by osctl", ""]));
    }

    [Theory]
    [InlineData("plain", "plain")]
    [InlineData("two words", "two words")]
    [InlineData("", "\"\"")]
    [InlineData(" leading", "\" leading\"")]
    [InlineData("trailing ", "\"trailing \"")]
    [InlineData("a;b", "\"a;b\"")]
    [InlineData("# hash", "# hash")]
    [InlineData("${Const|BaseURL}", "${Const|BaseURL}")]
    public void QuotesOnlyWhenNeeded(string value, string written) =>
        Assert.Equal(written, IniWriter.FormatValue("S", new IniEntry("k", value, null)));

    [Theory]
    [InlineData("has \"quote\"")]
    [InlineData("line\nbreak")]
    public void RefusesValuesNiniCannotRead(string value) =>
        Assert.Throws<IniWriteException>(() => IniWriter.FormatValue("S", new IniEntry("k", value, null)));

    [Theory]
    [InlineData("S", "a=b")]
    [InlineData("S", ";k")]
    [InlineData("S", "[k")]
    [InlineData("S", "")]
    [InlineData("S]", "k")]
    public void RefusesNamesNiniCannotRead(string section, string key)
    {
        var doc = new IniDocument();
        doc.Set(section, key, "v");
        Assert.Throws<IniWriteException>(() => IniWriter.ToText(doc));
    }

    [Fact]
    public void RoundTrips()
    {
        var doc = new IniDocument();
        doc.Set("Region Defaults", "ExternalHostName", "SYSTEMIP");
        doc.Set("Region Defaults", "Empty", "");
        doc.Set("DatabaseService", "ConnectionString", "Data Source=localhost;Database=opensim_Test1;");
        doc.Set("Const", "Spaced", "  x  ");

        var back = IniParser.Parse(IniWriter.ToText(doc));
        foreach (var section in doc.Sections)
            foreach (var entry in section.Entries)
                Assert.Equal(entry.Value, back.Get(section.Name, entry.Key));
        Assert.Equal(doc.Sections.Select(s => s.Name), back.Sections.Select(s => s.Name));
    }

    [Fact]
    public void WriteFileReplacesAtomically()
    {
        using var dir = new TempDir();
        var path = Path.Combine(dir.Path, "sub", "out.ini");
        var doc = new IniDocument();
        doc.Set("S", "k", "1");
        IniWriter.WriteFile(path, doc);
        doc.Set("S", "k", "2");
        IniWriter.WriteFile(path, doc);

        Assert.Equal("2", IniParser.ParseFile(path).Get("S", "k"));
        Assert.False(File.Exists(path + ".tmp"));
    }
}
